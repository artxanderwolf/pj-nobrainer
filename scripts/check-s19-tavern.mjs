import assert from 'node:assert/strict';
import {createInitialCityLayout} from '../src/app/game/city-layout-core.ts';
import {
  berlinCalendarDate, weightedTavernChoice, synchronizeTavernOffers, refreshAllTavernsOncePerDay,
  availableTavernApplicants, consumeTavernApplicant, findTavernApplicant,
  TAVERN_CLASS_WEIGHTS, TAVERN_RACE_WEIGHTS
} from '../src/app/game/tavern-offers-core.ts';
assert.deepEqual(TAVERN_CLASS_WEIGHTS.map(e=>e[1]),[35,25,20,20]);
assert.deepEqual(TAVERN_RACE_WEIGHTS.map(e=>e[1]),[30,20,20,10,20]);
assert.deepEqual(TAVERN_RACE_WEIGHTS.map(e=>e[0]),['human','dwarf','wood-elf','high-elf','halfling']);
assert.equal(weightedTavernChoice(TAVERN_CLASS_WEIGHTS,0),'recruit');
assert.equal(weightedTavernChoice(TAVERN_CLASS_WEIGHTS,.35),'fighter');
assert.equal(weightedTavernChoice(TAVERN_CLASS_WEIGHTS,.60),'archer');
assert.equal(weightedTavernChoice(TAVERN_CLASS_WEIGHTS,.80),'scholar');
assert.equal(weightedTavernChoice(TAVERN_RACE_WEIGHTS,.90),'halfling');
const timestamp=s=>Date.parse(s);
assert.equal(berlinCalendarDate(timestamp('2026-03-28T22:59:59Z')),'2026-03-28');
assert.equal(berlinCalendarDate(timestamp('2026-03-28T23:00:00Z')),'2026-03-29');
assert.equal(berlinCalendarDate(timestamp('2026-03-29T00:59:59Z')),'2026-03-29');
assert.equal(berlinCalendarDate(timestamp('2026-03-29T01:00:00Z')),'2026-03-29');
assert.equal(berlinCalendarDate(timestamp('2026-10-24T21:59:59Z')),'2026-10-24');
assert.equal(berlinCalendarDate(timestamp('2026-10-24T22:00:00Z')),'2026-10-25');
assert.equal(berlinCalendarDate(timestamp('2026-10-25T01:00:00Z')),'2026-10-25');
assert.equal(berlinCalendarDate(timestamp('2026-10-25T23:00:00Z')),'2026-10-26');
const state={cityLayout:createInitialCityLayout()};
const tavern=state.cityLayout.buildings.find(b=>b.buildingTypeId==='tavern');
assert.ok(tavern);
state.cityLayout.buildings.push({...tavern,buildingInstanceId:'building-7',x:6,y:2});
const first=timestamp('2026-10-25T00:45:00Z'), next=timestamp('2026-10-25T23:00:00Z');
let draws=0;const random=()=>{draws++;return draws%3===0?.82:.03;};
assert.equal(synchronizeTavernOffers(state,first,random),true);
assert.equal(draws,8,'Two distinct rolls for each of four offers');
const a=availableTavernApplicants(state,tavern.buildingInstanceId);
const b=availableTavernApplicants(state,'building-7');
assert.equal(a.length,2);
assert.equal(b.length,2);
assert.equal(new Set([...a,...b].map(x=>x.applicantId)).size,4);
assert.equal(synchronizeTavernOffers(state,first,random),false,'No reroll on open/tick');
assert.equal(draws,8);
const hired=a[0].applicantId;
assert.ok(findTavernApplicant(state,hired));
assert.equal(consumeTavernApplicant(state,hired),true);
assert.equal(consumeTavernApplicant(state,hired),false,'Cannot recruit twice');
assert.equal(availableTavernApplicants(state,tavern.buildingInstanceId).length,1);
const snapshot=JSON.stringify(state);
assert.equal(synchronizeTavernOffers(state,timestamp('2026-10-25T01:30:00Z'),random),false,'DST overlap must not reroll');
assert.equal(JSON.stringify(state),snapshot,'Reopen retains offers');
assert.equal(refreshAllTavernsOncePerDay(state,first,random),true);
assert.equal(availableTavernApplicants(state,tavern.buildingInstanceId).length,2);
const afterManual=JSON.stringify(state);
assert.equal(refreshAllTavernsOncePerDay(state,first,random),false,'Only once per Berlin day globally');
assert.equal(JSON.stringify(state),afterManual);
const oldIds=Object.values(state.tavernOffers.byBuildingId).flat().map(x=>x.applicantId);
const reloaded=JSON.parse(JSON.stringify(state));
assert.equal(synchronizeTavernOffers(reloaded,first,random),false,'Save reload is stable');
assert.equal(refreshAllTavernsOncePerDay(reloaded,first,random),false,'Manual refresh persists');
assert.equal(synchronizeTavernOffers(reloaded,next,random),true,'Offline date boundary refresh');
assert.equal(reloaded.tavernOffers.berlinDate,'2026-10-26');
assert.equal(Object.values(reloaded.tavernOffers.byBuildingId).flat().length,4);
assert.ok(Object.values(reloaded.tavernOffers.byBuildingId).flat().every(x=>!oldIds.includes(x.applicantId)));
assert.equal(refreshAllTavernsOncePerDay(reloaded,next,random),true,'New date gets new manual refresh');
console.log('S19: Berlin CET/CEST midnight and fall-back, stable offers/IDs, independent 35/25/20/20 & 30/20/20/10/20 rolls, global refresh and single-use recruiting passed.');
