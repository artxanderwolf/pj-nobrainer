import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { validateFromDisk } from './validate-game-data.mjs';

const OUTPUT_DIR = resolve('src/app/game/data/generated');
const STAT_FIELDS = {
  hp: 'hp', energy: 'energy', armor: 'armor', dodge: 'dodge',
  strengthFactor: 'strength_factor', precision: 'precision', threat: 'threat',
  critChance: 'crit_chance', critDamage: 'crit_damage', hpRegenPerMinute: 'hp_regen_per_min',
  energyRegenPerMinute: 'energy_regen_per_min', experienceFactor: 'experience_factor',
  lifeSteal: 'life_steal', penetration: 'penetration'
};
const FORM_STAT_FIELDS = {
  hp: 'mod_hp', energy: 'mod_energy', armor: 'mod_armor', dodge: 'mod_dodge',
  strengthFactor: 'mod_strength_factor', precision: 'mod_precision', threat: 'mod_threat',
  critChance: 'mod_crit_chance', critDamage: 'mod_crit_damage', hpRegenPerMinute: 'mod_hp_regen_per_min',
  energyRegenPerMinute: 'mod_energy_regen_per_min', experienceFactor: 'mod_experience_factor',
  lifeSteal: 'mod_life_steal', penetration: 'mod_penetration'
};

const n = value => Number(value) || 0;
const split = value => String(value ?? '').split('|').map(item => item.trim()).filter(Boolean);
const objectFromRows = (rows, keyField, valueField) => Object.fromEntries(rows.map(row => [row[keyField], row[valueField]]));
const fullStats = (row, mapping = STAT_FIELDS) => Object.fromEntries(Object.entries(mapping).map(([key, column]) => [key, n(row[column])]));
const header = '/* AUTO-GENERATED by scripts/data/build-game-data.mjs. Do not edit directly. */\n';
const ts = (name, value) => `export const ${name} = ${JSON.stringify(value)} as const;\n`;

function buildGameData(tables) {
  const meta = tables._meta.rows[0];
  const settings = objectFromRows(tables.game_settings.rows, 'key', 'value');
  const upgrades = Object.fromEntries(tables.upgrades.rows.map(row => {
    const config = { baseCostNickel: n(row.base_cost_nickel), growth: n(row.growth) };
    config[String(row.start_property)] = n(row.start_value);
    config[String(row.start_property) === 'startCapacity' ? 'maxCapacity' : 'max'] = n(row.max_value);
    return [String(row.id), config];
  }));

  const partTemplates = Object.fromEntries(tables.weapon_parts.rows.map(row => [String(row.part_id), {
    id: String(row.part_id),
    label: String(row.label),
    materialSlot: String(row.material_slot),
    categories: split(row.categories),
    statKeys: split(row.stat_keys)
  }]));

  const formParts = new Map();
  for (const row of tables.weapon_form_parts.rows) {
    const formId = String(row.weapon_form_id);
    const list = formParts.get(formId) ?? [];
    list.push({ ...partTemplates[String(row.part_id)], quantity: n(row.quantity) });
    formParts.set(formId, list);
  }

  const weaponForms = Object.fromEntries(tables.weapon_forms.rows.map(row => [String(row.id), {
    name: String(row.display_name),
    oneHanded: Boolean(row.one_handed),
    timeFactor: n(row.time_factor),
    baseDamage: n(row.base_damage),
    baseSpeed: n(row.base_speed),
    baseHitChance: n(row.base_hit_chance),
    basePenetration: n(row.base_penetration),
    characterModifiers: fullStats(row, FORM_STAT_FIELDS),
    damageFactor: 1,
    speedFactor: 1,
    parts: formParts.get(String(row.id)) ?? []
  }]));

  const dungeon = tables.dungeons.rows[0];
  const dungeonId = n(dungeon.dungeon_id);
  const classWeights = Object.fromEntries(
    tables.dungeon_enemy_weights.rows
      .filter(row => n(row.dungeon_id) === dungeonId)
      .map(row => [String(row.class_id), n(row.weight)])
  );
  const enemyCountWeights = {};
  for (let teamSize = 1; teamSize <= 4; teamSize += 1) {
    enemyCountWeights[teamSize] = tables.dungeon_enemy_counts.rows
      .filter(row => n(row.dungeon_id) === dungeonId && n(row.team_size) === teamSize)
      .sort((a, b) => n(a.enemy_count) - n(b.enemy_count))
      .map(row => n(row.weight));
  }

  const config = {
    dungeon: {
      id: dungeonId,
      energyCost: n(dungeon.energy_cost),
      durationMs: n(dungeon.duration_ms),
      enemyBase: {
        damage: n(dungeon.enemy_base_damage), speed: n(dungeon.enemy_base_speed),
        hitChance: n(dungeon.enemy_base_hit_chance), penetration: n(dungeon.enemy_base_penetration)
      },
      enemyMultipliers: {
        hp: n(dungeon.enemy_mult_hp), armor: n(dungeon.enemy_mult_armor), dodge: n(dungeon.enemy_mult_dodge),
        damage: n(dungeon.enemy_mult_damage), speed: n(dungeon.enemy_mult_speed),
        hitChance: n(dungeon.enemy_mult_hit_chance), penetration: n(dungeon.enemy_mult_penetration)
      },
      encounterChance: n(dungeon.encounter_chance),
      searchStepMs: n(dungeon.search_step_ms),
      lootCollectMs: n(dungeon.loot_collect_ms),
      enemyClassWeights: classWeights,
      enemyCountWeights
    },
    energyRegenPerMinute: n(settings.energyRegenPerMinute),
    market: { baseSeconds: n(settings['market.baseSeconds']), materialBaseNickel: n(settings['market.materialBaseNickel']) },
    tavern: { recruitBaseNickel: n(settings['tavern.recruitBaseNickel']), recruitGrowth: n(settings['tavern.recruitGrowth']) },
    upgrades,
    forge: { baseSeconds: n(settings['forge.baseSeconds']), weaponForms }
  };

  const classes = Object.fromEntries(tables.character_classes.rows.map(row => [String(row.id), {
    id: String(row.id), name: String(row.display_name), maxHp: n(row.max_hp), maxEnergy: n(row.max_energy),
    dodge: n(row.dodge), armor: n(row.armor), strengthFactor: n(row.strength_factor), precision: n(row.precision),
    threat: n(row.threat), critChance: n(row.crit_chance), critDamage: n(row.crit_damage),
    hpRegenPerMinute: n(row.hp_regen_per_min), energyRegenPerMinute: n(row.energy_regen_per_min),
    experienceFactor: n(row.experience_factor), lifeSteal: n(row.life_steal), penetration: n(row.penetration),
    distance: n(row.distance), role: String(row.role)
  }]));

  const materials = Object.fromEntries(tables.materials.rows.map(row => {
    const specialStat = String(row.special_stat || '');
    const specialEffect = specialStat ? { stat: specialStat, amount: n(row.special_amount) } : null;
    let reinforcement = null;
    if (specialEffect?.stat === 'GES') reinforcement = { speedFactor: 1 + specialEffect.amount };
    if (specialEffect?.stat === 'DS') reinforcement = { penetrationAdd: specialEffect.amount };
    if (specialEffect?.stat === 'P') reinforcement = { hitChanceAdd: specialEffect.amount };
    return [String(row.display_name), {
      materialId: n(row.material_id),
      dungeonDropWeight: n(row.dungeon_drop_weight),
      category: String(row.category),
      rarity: n(row.rarity),
      stats: fullStats(row),
      specialEffect,
      baseDamage: null,
      baseSpeed: null,
      blade: null,
      penetration: null,
      gripSpeed: null,
      hitChance: null,
      reinforcement
    }];
  }));

  const rarityBonus = Object.fromEntries(tables.rarity_balance.rows.map(row => [n(row.rarity), n(row.sale_bonus)]));

  const enemyLoot = new Map();
  for (const row of tables.dungeon_enemy_loot.rows) {
    const key = `${n(row.dungeon_id)}:${String(row.class_id)}`;
    const list = enemyLoot.get(key) ?? [];
    list.push({ order: n(row.order), materialId: n(row.material_id) });
    enemyLoot.set(key, list);
  }
  const enemyDefinitions = {};
  for (const row of tables.dungeon_enemies.rows) {
    const did = n(row.dungeon_id);
    const classId = String(row.class_id);
    enemyDefinitions[did] ??= {};
    enemyDefinitions[did][classId] = {
      name: String(row.display_name),
      lootMaterialIds: (enemyLoot.get(`${did}:${classId}`) ?? []).sort((a,b) => a.order - b.order).map(item => item.materialId),
      xpDrop: n(row.xp_drop)
    };
  }

  const categoryOrder = tables.dungeon_category_weights.rows.map(row => [n(row.dungeon_id), String(row.category), n(row.weight)]);
  const legacyLoot = {};
  for (const [did, category, weight] of categoryOrder) {
    legacyLoot[did] ??= { categories: [] };
    legacyLoot[did].categories.push({
      name: category,
      weight,
      items: Object.entries(materials)
        .filter(([, definition]) => definition.category === category)
        .sort((a,b) => b[1].dungeonDropWeight - a[1].dungeonDropWeight || a[1].materialId - b[1].materialId)
        .map(([name, definition]) => ({ name, chance: definition.dungeonDropWeight }))
    });
  }

  return {
    meta: { schemaVersion: n(meta.schema_version), contentRevision: n(meta.content_revision), baselineVersion: String(meta.baseline_version) },
    config, classes, materials, rarityBonus, enemyDefinitions, legacyLoot, materialKeys: tables.materials.rows.map(row => ({
      materialId: n(row.material_id), technicalKey: String(row.technical_key), displayName: String(row.display_name)
    }))
  };
}

function buildEconomy(tables) {
  const values = objectFromRows(tables.economy_balance.rows, 'key', 'value');
  return {
    progressionCostMultiplier: n(values.progressionCostMultiplier),
    positiveSpecialMaterialValueFactor: n(values.positiveSpecialMaterialValueFactor),
    materialSaleBaseSeconds: n(values.materialSaleBaseSeconds),
    materialSaleSecondsPerNickel: n(values.materialSaleSecondsPerNickel),
    weaponArmorBenchmarks: split(values.weaponArmorBenchmarks).map(n),
    weaponBaseValueNickel: n(values.weaponBaseValueNickel),
    weaponValuePerPerformance: n(values.weaponValuePerPerformance),
    weaponValueRoundStepNickel: n(values.weaponValueRoundStepNickel),
    weaponForgeBaseSeconds: n(values.weaponForgeBaseSeconds),
    weaponForgeSecondsPerNickel: n(values.weaponForgeSecondsPerNickel),
    weaponSaleBaseSeconds: n(values.weaponSaleBaseSeconds),
    weaponSaleSecondsPerNickel: n(values.weapon_sale_seconds_per_nickel),
    timeRoundStepSeconds: n(values.timeRoundStepSeconds)
  };
}

function buildProgression(tables) {
  const row = tables.character_progression.rows[0];
  return {
    CHARACTER_LEVEL_MAX: n(row.max_level),
    CHARACTER_XP_BASE: n(row.xp_base),
    CHARACTER_XP_GROWTH: n(row.xp_growth),
    CHARACTER_STAT_GROWTH: n(row.stat_growth)
  };
}

const tables = await validateFromDisk();
const game = buildGameData(tables);
const economy = buildEconomy(tables);
const progression = buildProgression(tables);
await mkdir(OUTPUT_DIR, { recursive: true });

const gameSource = header
  + ts('DATA_META', game.meta)
  + ts('GENERATED_CONFIG', game.config)
  + ts('GENERATED_CHARACTER_CLASSES', game.classes)
  + ts('GENERATED_MATERIAL_SALE_RARITY_BONUS', game.rarityBonus)
  + ts('GENERATED_MATERIALS', game.materials)
  + ts('GENERATED_DUNGEON_ENEMY_DEFINITIONS', game.enemyDefinitions)
  + ts('GENERATED_DUNGEON_LOOT_TABLES', game.legacyLoot)
  + ts('GENERATED_MATERIAL_KEYS', game.materialKeys);

const economySource = header + ts('GENERATED_ECONOMY_BALANCE', economy);
const progressionSource = header + Object.entries(progression).map(([key, value]) => `export const ${key} = ${JSON.stringify(value)};\n`).join('');

await writeFile(resolve(OUTPUT_DIR, 'game-data.generated.ts'), gameSource, 'utf8');
await writeFile(resolve(OUTPUT_DIR, 'economy-balance.generated.ts'), economySource, 'utf8');
await writeFile(resolve(OUTPUT_DIR, 'character-progression.generated.ts'), progressionSource, 'utf8');
console.log('NoBrainer-Datentabellen: TypeScript-Daten erfolgreich erzeugt.');